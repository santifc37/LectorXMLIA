const git = (...args) =>
  execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()

function fallar(mensaje) {
  console.error('\n✖ ' + mensaje)
  process.exit(1)
}

try {
  git('rev-parse', '--is-inside-work-tree')
} catch {
  fallar('Ejecuta este script dentro de la carpeta del repositorio LectorXMLIA.')
}

const rama = git('rev-parse', '--abbrev-ref', 'HEAD')
if (rama !== 'master') fallar('Estás en la rama "' + rama + '". Cambia a master: git checkout master')

if (git('status', '--porcelain')) {
  fallar('Hay cambios sin guardar. Haz commit o git stash antes de continuar.')
}

const carpeta = mkdtempSync(join(tmpdir(), 'fases-'))
const archivo = join(carpeta, 'fases.patch')
writeFileSync(archivo, Buffer.from(PATCH_BASE64.replace(/\s+/g, ''), 'base64'))

try {
  console.log('Aplicando las 4 fases...')
  git('-c', 'user.name=' + (safe(() => git('config', 'user.name')) || 'Importador'),
      '-c', 'user.email=' + (safe(() => git('config', 'user.email')) || 'importador@local'),
      'am', '--3way', archivo)
} catch (error) {
  try { git('am', '--abort') } catch {}
  fallar('No se pudo aplicar (¿master tiene cambios nuevos?):\n' + (error.stderr || error.message))
} finally {
  rmSync(carpeta, { recursive: true, force: true })
}

function safe(fn) {
  try { return fn() } catch { return '' }
}

console.log('\n✔ Listo. Commits creados:\n')
console.log(git('log', '--oneline', '-4'))

